#!/usr/bin/env python3
"""Runs the DTN benchmarks: The ONE's routers and Mycel's carrier on identical
contact traces and message workloads (docs/BENCHMARKS.md).

  bench/fetch.sh                 # tools and traces (once)
  bench/one/one.sh build         # compile The ONE (once)
  cargo build --profile replay -p mycel-bench   # (speed-optimised; --release works too)
  bench/run.py                   # everything below, skipping what exists
  bench/run.py --only cambridge  # one scenario
  bench/run.py --force           # redo all runs
  bench/run.py --routers mycel --force   # re-run Mycel only (after changing
                                         # crates/mycel-net/src/mesh/dtn.rs)
  bench/run.py --summary-only    # tables from existing results

Stages: traces -> Helsinki capture -> workloads + ONE event files + ONE
settings -> ONE runs and Mycel runs (in parallel) -> results/summary.{csv,md}.
"""
import argparse
import concurrent.futures as cf
import csv
import os
import re
import subprocess
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
CONVERT = [sys.executable, os.path.join(HERE, "traces", "convert.py")]
OUT = os.path.join(HERE, "traces", "out")
RESULTS = os.path.join(HERE, "results")
GEN = os.path.join(HERE, "one", "gen")
REPLAY = os.environ.get("MYCEL_REPLAY") or next(
    (p for p in (os.path.join(ROOT, "target", d, "dtn-replay") for d in ("replay", "release")) if os.path.exists(p)),
    os.path.join(ROOT, "target", "release", "dtn-replay"))

ROUTERS = ["EpidemicRouter", "ProphetRouter", "SprayAndWaitRouter", "MaxPropRouter", "DirectDeliveryRouter"]

# name -> (source, nodes, gateways)
SCENARIOS = {
    "cambridge": ("crawdad:cambridge/contacts.Exp2.dat:12", 12, ""),
    "infocom2005": ("crawdad:infocom2005/contacts.Exp3.dat:41", 41, ""),
    "infocom2006": ("crawdad:infocom2006/contacts.Exp6.dat:98", 98, ""),
    # the 17 static long-range iMotes have "the internet"
    "infocom2006-gw": ("same:infocom2006", 98, "0-16"),
    "helsinki": ("one:helsinki", 126, ""),
    # the 6 trams have "the internet"
    "helsinki-gw": ("same:helsinki", 126, "120-125"),
}

# name -> (interval s, size bytes, TTL minutes)
WORKLOADS = {
    # ONE's default_settings.txt
    "heavy": ("25,35", "500000,1000000", 300),
    # chat-sized messages, a day to arrive
    "chat": ("25,35", "1000,10000", 1440),
}


def sh(cmd, **kw):
    r = subprocess.run(cmd, capture_output=True, text=True, **kw)
    if r.returncode != 0:
        raise RuntimeError(f"{' '.join(cmd)} failed:\n{r.stdout[-2000:]}\n{r.stderr[-2000:]}")
    return r.stdout


def trace_name(scen):
    src = SCENARIOS[scen][0]
    return src.split(":")[1] if src.startswith("same:") else scen


def prepare_trace(scen, force):
    src, _, _ = SCENARIOS[scen]
    out = os.path.join(OUT, f"{scen}.csv")
    if src.startswith("same:") or (os.path.exists(out) and not force):
        return
    kind, rest = src.split(":", 1)
    if kind == "crawdad":
        path, internal = rest.rsplit(":", 1)
        sh(CONVERT + ["crawdad", os.path.join(HERE, "data", path), "--internal-max", internal,
                      "--out", out, "--map", os.path.join(OUT, f"{scen}-ids.csv")])
    elif kind == "one":
        conn = os.path.join(RESULTS, "helsinki-capture", "helsinki-capture_ConnectivityONEReport.txt")
        if not os.path.exists(conn) or force:
            sh(["bash", os.path.join(HERE, "one", "one.sh"), "run", "1", "helsinki-capture.txt"])
        sh(CONVERT + ["one-conn", conn, "--end", "43200", "--out", out])


def end_time(scen):
    with open(os.path.join(OUT, f"{trace_name(scen)}.csv")) as f:
        return max(float(r["t_end"]) for r in csv.DictReader(f))


def prepare_run(scen, wl, force):
    """Messages, ONE events and ONE settings for one (scenario, workload)."""
    trace = trace_name(scen)
    _, nodes, gws = SCENARIOS[scen]
    interval, size, ttl = WORKLOADS[wl]
    msgs = os.path.join(OUT, f"{trace}-{wl}-msgs.csv")
    if not os.path.exists(msgs) or force:
        sh(CONVERT + ["workload", "--contacts", os.path.join(OUT, f"{trace}.csv"), "--nodes", str(nodes),
                      "--interval", interval, "--size", size, "--seed", "1", "--out", msgs])
    events = os.path.join(OUT, f"{scen}-{wl}.events")
    if not os.path.exists(events) or force:
        cmd = CONVERT + ["one-events", "--contacts", os.path.join(OUT, f"{trace}.csv"), "--messages", msgs, "--out", events]
        if gws:
            cmd += ["--gateways", gws]
        sh(cmd)
    os.makedirs(GEN, exist_ok=True)
    name = f"{scen}-{wl}"
    with open(os.path.join(GEN, f"{name}.txt"), "w") as f:
        f.write(f"# generated by bench/run.py: {scen}, workload {wl}; use with trace-common.txt\n")
        f.write(f"Scenario.name = {name}-%%Group.router%%\n")
        f.write(f"Scenario.endTime = {int(end_time(scen)) + 1}\n")
        f.write(f"Group.nrofHosts = {nodes}\n")
        f.write(f"Group.msgTtl = {ttl}\n")
        f.write(f"Events1.filePath = ../../traces/out/{scen}-{wl}.events\n")
        f.write(f"Report.reportDir = ../../results/one/{name}\n")
    return name, msgs


def complete(report):
    """ONE writes a report when its run ends; a killed run leaves it empty."""
    try:
        return "rtt_med" in open(report).read()
    except OSError:
        return False


def run_one(name, force):
    d = os.path.join(RESULTS, "one", name)
    todo = ROUTERS if force else [
        r for r in ROUTERS if not complete(os.path.join(d, f"{name}-{r}_MessageStatsReport.txt"))]
    if not todo:
        return name
    settings = ["trace-common.txt", f"gen/{name}.txt"]
    if todo != ROUTERS:
        # Resume: run only the routers without a finished report (later
        # settings files override earlier ones).
        with open(os.path.join(GEN, f"{name}-rest.txt"), "w") as f:
            f.write(f"Group.router = [{'; '.join(todo)}]\n")
        settings.append(f"gen/{name}-rest.txt")
    log = sh(["bash", os.path.join(HERE, "one", "one.sh"), "run", str(len(todo))] + settings)
    os.makedirs(d, exist_ok=True)
    with open(os.path.join(d, "run.log"), "w" if todo == ROUTERS else "a") as f:
        f.write(log)
    return name


def run_mycel(scen, wl, msgs, force):
    name = f"{scen}-{wl}"
    out = os.path.join(RESULTS, "mycel", f"{name}.txt")
    if os.path.exists(out) and not force:
        return name
    _, _, gws = SCENARIOS[scen]
    _, _, ttl = WORKLOADS[wl]
    cmd = [REPLAY, "--contacts", os.path.join(OUT, f"{trace_name(scen)}.csv"), "--messages", msgs,
           "--ttl-min", str(ttl), "--label", f"{name}-Mycel", "--latencies", out.replace(".txt", "-lat.csv")]
    if gws:
        cmd += ["--gateways", gws]
    r = subprocess.run(cmd, capture_output=True, text=True)
    if r.returncode != 0:
        raise RuntimeError(f"mycel {name}: {r.stderr[-2000:]}")
    os.makedirs(os.path.dirname(out), exist_ok=True)
    open(out, "w").write(r.stdout + "# " + r.stderr)
    return name


def parse_stats(path):
    stats = {}
    for line in open(path):
        m = re.match(r"^(\w+): (.*)$", line.strip())
        if m:
            stats[m.group(1)] = m.group(2)
    return stats


WITHIN = [60, 600, 3600]


def within_one(path, created):
    """% of created messages delivered within each WITHIN, from ONE's
    DeliveredMessagesReport (column 5 is the delivery latency)."""
    lat = [float(line.split()[4]) for line in open(path) if line.strip() and not line.startswith("#")]
    return [100 * sum(1 for x in lat if x <= w) / created for w in WITHIN]


def within_mycel(path):
    rows = list(csv.DictReader(open(path)))
    return [100 * sum(1 for r in rows if r["latency_s"] and float(r["latency_s"]) <= w) / len(rows) for w in WITHIN]


def speed_rows(names):
    """(scenario, workload, router, [% within each WITHIN]) where per-message data exists."""
    out = []
    for name in names:
        scen, wl = name.rsplit("-", 1)
        for r in ROUTERS:
            stats = os.path.join(RESULTS, "one", name, f"{name}-{r}_MessageStatsReport.txt")
            dm = os.path.join(RESULTS, "one", name, f"{name}-{r}_DeliveredMessagesReport.txt")
            if complete(stats) and os.path.exists(dm):
                out.append((scen, wl, r.replace("Router", ""), within_one(dm, int(parse_stats(stats)["created"]))))
        lat = os.path.join(RESULTS, "mycel", f"{name}-lat.csv")
        if os.path.exists(lat):
            out.append((scen, wl, "Mycel", within_mycel(lat)))
    return out


def summarize(names):
    rows = []
    for name in names:
        scen, wl = name.rsplit("-", 1)
        for r in ROUTERS:
            p = os.path.join(RESULTS, "one", name, f"{name}-{r}_MessageStatsReport.txt")
            if os.path.exists(p):
                rows.append((scen, wl, r.replace("Router", ""), parse_stats(p)))
        p = os.path.join(RESULTS, "mycel", f"{name}.txt")
        if os.path.exists(p):
            rows.append((scen, wl, "Mycel", parse_stats(p)))
    cols = ["delivery_prob", "latency_avg", "latency_med", "overhead_ratio", "hopcount_avg", "created", "delivered", "relayed"]
    with open(os.path.join(RESULTS, "summary.csv"), "w", newline="") as f:
        w = csv.writer(f)
        w.writerow(["scenario", "workload", "router"] + cols)
        for scen, wl, r, s in rows:
            w.writerow([scen, wl, r] + [s.get(c, "") for c in cols])
    with open(os.path.join(RESULTS, "summary.md"), "w") as f:
        for wl in WORKLOADS:
            f.write(f"\n### Workload: {wl}\n\n")
            f.write("| Scenario | Router | Delivered | Latency avg (s) | Latency median (s) | Overhead | Hops avg |\n")
            f.write("|---|---|---:|---:|---:|---:|---:|\n")
            for scen, w_, r, s in rows:
                if w_ != wl:
                    continue
                num = lambda k, d=0: (f"{float(s[k]):.{d}f}" if s.get(k) not in (None, "", "NaN", "nan") else "–")
                dp = f"{100 * float(s['delivery_prob']):.1f} %" if s.get("delivery_prob") else "–"
                bold = "**" if r == "Mycel" else ""
                f.write(f"| {scen} | {bold}{r}{bold} | {dp} | {num('latency_avg')} | {num('latency_med')} | "
                        f"{num('overhead_ratio', 2)} | {num('hopcount_avg', 2)} |\n")
        speed = speed_rows(names)
        if speed:
            f.write("\n### Delivered within a time, as a share of all messages created\n\n")
            f.write("| Scenario | Workload | Router | ≤ 1 min | ≤ 10 min | ≤ 1 h |\n|---|---|---|---:|---:|---:|\n")
            for scen, wl, r, v in speed:
                bold = "**" if r == "Mycel" else ""
                f.write(f"| {scen} | {wl} | {bold}{r}{bold} | " + " | ".join(f"{x:.1f} %" for x in v) + " |\n")
    print(open(os.path.join(RESULTS, "summary.md")).read())


def main():
    p = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    p.add_argument("--only", nargs="*", help="scenarios")
    p.add_argument("--workloads", nargs="*", default=list(WORKLOADS))
    p.add_argument("--force", action="store_true", help="redo the simulation runs")
    p.add_argument("--rebuild-inputs", action="store_true", help="regenerate traces, workloads and ONE event files")
    p.add_argument("--routers", choices=["both", "one", "mycel"], default="both")
    p.add_argument("--jobs", type=int, default=4)
    p.add_argument("--summary-only", action="store_true")
    a = p.parse_args()
    scens = a.only or list(SCENARIOS)
    os.makedirs(OUT, exist_ok=True)
    names = [f"{s}-{w}" for s in scens for w in a.workloads]
    if not a.summary_only:
        for s in scens:
            prepare_trace(trace_name(s), a.rebuild_inputs)
        prepared = [(s, w, *prepare_run(s, w, a.rebuild_inputs)) for s in scens for w in a.workloads]
        with cf.ThreadPoolExecutor(a.jobs) as ex:
            futs = []
            if a.routers in ("both", "mycel"):
                futs += [ex.submit(run_mycel, s, w, msgs, a.force) for s, w, _, msgs in prepared]
            if a.routers in ("both", "one"):
                futs += [ex.submit(run_one, name, a.force) for _, _, name, _ in prepared]
            for fu in cf.as_completed(futs):
                print("done", fu.result(), flush=True)
    summarize(names)


if __name__ == "__main__":
    main()
